import { Type } from 'class-transformer';
import {
  IsEnum,
  IsInt,
  IsOptional,
  IsString,
  Max,
  MaxLength,
  Min,
} from 'class-validator';

/**
 * The order lifecycle.
 *
 * The full set is declared here, and only two states are REACHABLE in step 1
 * of this milestone. That is deliberate: the enum is the contract clients
 * code against, and adding states to a published contract later is a
 * breaking change, while declaring an unreachable state costs nothing.
 *
 *   CONFIRMED   the order was accepted.        ← where step 1 starts
 *   CANCELLED   the customer called it off.    ← the only transition today
 *
 *   PENDING     created, but the workflow has not finished.   step 2
 *   FAILED      the workflow could not finish and could not
 *               fully undo itself.                            step 2
 *   PAID        payment captured.                             M9
 *   PROCESSING · SHIPPED · DELIVERED                           M10+
 *
 * Step 1 has no workflow, so an order is CONFIRMED the moment it is written.
 * PENDING only becomes meaningful when there are steps that can be halfway
 * done — which is exactly what step 2 of this milestone introduces.
 */
export enum OrderStatus {
  Pending = 'PENDING',
  Confirmed = 'CONFIRMED',
  Paid = 'PAID',
  Processing = 'PROCESSING',
  Shipped = 'SHIPPED',
  Delivered = 'DELIVERED',
  Cancelled = 'CANCELLED',
  Failed = 'FAILED',
}

/**
 * One line of an order — a SNAPSHOT of the cart line, which was itself a
 * snapshot of the catalogue.
 *
 * `lineTotal` is STORED, unlike in the cart where it is derived on every
 * read. The difference is what the two records are for: a cart is a working
 * document, and an order is a financial record that must still say the same
 * number in five years, even if the arithmetic in this repository changes.
 * A CHECK constraint keeps the stored value honest.
 */
export class OrderItemDto {
  id!: string;

  productId!: string;

  sku!: string;

  name!: string;

  unitPrice!: string;

  quantity!: number;

  lineTotal!: string;
}

export class OrderDto {
  id!: string;

  /**
   * The human-facing reference: `ORD-00000042`.
   *
   * A separate identifier from the UUID on purpose. A customer has to read
   * this one out over the phone, and "eight-e-four-dash-be-one-two…" is not
   * something anyone can do. It is generated by a PostgreSQL sequence, so
   * two concurrent checkouts cannot receive the same number.
   *
   * It is NOT a secret and NOT a permission: every order route is scoped to
   * the authenticated user, so guessing `ORD-00000043` reveals nothing.
   */
  orderNumber!: string;

  userId!: string;

  status!: OrderStatus;

  items!: OrderItemDto[];

  subtotal!: string;

  total!: string;

  currency!: string;

  /** Present once the order has been cancelled. */
  cancelReason?: string | null;

  createdAt!: Date;

  updatedAt!: Date;
}

/**
 * The checkout request — deliberately empty.
 *
 * NOTE WHAT IS ABSENT: no items, no prices, no userId. The order is built
 * from the SERVER's view of the cart and the verified identity of the
 * caller. A client that could name its own lines would order a £900 laptop
 * at a price of its choosing.
 *
 * The class exists even with no fields, because the global ValidationPipe
 * uses `forbidNonWhitelisted`: a body with anything in it is a 400 rather
 * than something quietly ignored.
 */
export class CreateOrderDto {}

export class CancelOrderDto {
  /**
   * Why the customer is cancelling. Optional and free text — this is
   * analytics, not a state machine input.
   */
  @IsOptional()
  @IsString()
  @MaxLength(200)
  reason?: string;
}

export class QueryOrdersDto {
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  page?: number;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(100)
  limit?: number;

  @IsOptional()
  @IsEnum(OrderStatus)
  status?: OrderStatus;
}
