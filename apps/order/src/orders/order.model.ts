import { OrderStatus } from '@ecommerce/contracts';
import {
  Column,
  CreatedAt,
  DataType,
  HasMany,
  Model,
  Table,
  UpdatedAt,
} from 'sequelize-typescript';
import { OrderItem } from './order-item.model';

/**
 * An order.
 *
 * NEVER DELETED, and never edited in place beyond its status. An order is a
 * financial record: it is what the business claims happened, and it has to
 * survive being wrong. A cancelled order stays, with a reason, because
 * "there is no row" and "there was a row and it was cancelled" answer very
 * different questions during a dispute.
 */
@Table({ tableName: 'orders', underscored: true, timestamps: true })
export class Order extends Model<Order> {
  @Column({
    type: DataType.UUID,
    primaryKey: true,
    allowNull: false,
    defaultValue: DataType.UUIDV4,
  })
  override id!: string;

  /**
   * Generated by the database sequence, so this model never sets it.
   *
   * That is why the insert in the repository lists its columns explicitly:
   * a model that "helpfully" sent `orderNumber: undefined` would override
   * the DEFAULT with NULL and hit the NOT NULL constraint.
   */
  @Column({ type: DataType.STRING(20), allowNull: false })
  orderNumber!: string;

  /** From the verified token at the gateway. Never from a request body. */
  @Column({ type: DataType.UUID, allowNull: false })
  userId!: string;

  @Column({ type: DataType.UUID, allowNull: false })
  cartId!: string;

  @Column({
    type: DataType.STRING(20),
    allowNull: false,
    defaultValue: OrderStatus.Confirmed,
  })
  status!: OrderStatus;

  @Column({ type: DataType.STRING(3), allowNull: false, defaultValue: 'USD' })
  currency!: string;

  /** DECIMAL comes back as a string from the pg driver. It stays one. */
  @Column({ type: DataType.DECIMAL(12, 2), allowNull: false })
  subtotal!: string;

  @Column({ type: DataType.DECIMAL(12, 2), allowNull: false })
  total!: string;

  @Column({ type: DataType.TEXT, allowNull: true })
  cancelReason!: string | null;

  @Column({ type: DataType.DATE, allowNull: true })
  cancelledAt!: Date | null;

  @HasMany(() => OrderItem)
  items!: OrderItem[];

  @CreatedAt
  override createdAt!: Date;

  @UpdatedAt
  override updatedAt!: Date;
}
